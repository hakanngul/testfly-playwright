import fs from 'node:fs';
import path from 'node:path';
import type { ParsedLocatorItem } from './types';
import { LocatorParser } from './LocatorParser';

const sq = (v: string): string => `'${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** Generates `index.d.ts` typings for locator keys. @public */
export class LocatorTypeGen {
  /**
   * Generate TypeScript declaration code from parsed locator items
   */
  static generateDts(items: ParsedLocatorItem[]): string {
    const keys = items.map((i) => sq(i.fullKey));
    const unionType = keys.length > 0 ? keys.join('\n  | ') : 'string';

    const lines: string[] = [
      '// Auto-generated by "testfly locators". DO NOT EDIT.',
      '',
      'declare global {',
      '  namespace TestFly {',
      '    interface LocatorMap {',
      ...items.map((i) => `      ${sq(i.fullKey)}: true;`),
      '    }',
      '  }',
      '}',
      '',
      `export type TestFlyLocatorKey = \n  | ${unionType};`,
      '',
      'export interface GeneratedLocatorRegistry {',
    ];

    // Group by page
    const byPage: Record<string, string[]> = {};
    for (const item of items) {
      if (!byPage[item.page]) byPage[item.page] = [];
      byPage[item.page].push(item.name);
    }

    for (const [page, names] of Object.entries(byPage)) {
      lines.push(`  ${sq(page)}: {`);
      for (const name of names) {
        lines.push(`    ${sq(name)}: ${sq(`${page}.${name}`)};`);
      }
      lines.push('  };');
    }

    lines.push('}');
    lines.push('');

    return lines.join('\n');
  }

  /**
   * Scan locators directory and write type declaration file
   */
  static generateToFile(locatorsDir: string, outputFile: string): { count: number; outputPath: string } {
    const items = LocatorParser.parseDirectory(locatorsDir);
    const dtsContent = this.generateDts(items);

    const outDir = path.dirname(outputFile);
    if (!fs.existsSync(outDir)) {
      fs.mkdirSync(outDir, { recursive: true });
    }

    fs.writeFileSync(outputFile, dtsContent, 'utf8');
    return {
      count: items.length,
      outputPath: outputFile,
    };
  }
}
