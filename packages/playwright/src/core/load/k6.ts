import { spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { TestFlyError } from '../errors';

/** One HTTP request the generated k6 script repeats. @public */
export interface LoadRequest {
  /** Absolute URL, or a path resolved against `baseUrl`. */
  url: string;
  method?: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE' | 'HEAD' | 'OPTIONS';
  headers?: Record<string, string>;
  /** Request body; objects are sent as JSON. */
  body?: string | Record<string, unknown> | unknown[];
}

/** Pass/fail limits; each one becomes a k6 threshold. @public */
export interface LoadThresholds {
  /** 95th percentile of `http_req_duration`, in ms. */
  p95Ms?: number;
  /** 99th percentile of `http_req_duration`, in ms. */
  p99Ms?: number;
  /** Highest allowed share of failed requests (`http_req_failed`), 0..1. */
  errorRate?: number;
}

/** Options of `load.run()`. Give either `url`/`requests` (a script is generated) or `script`. @public */
export interface LoadRunOptions extends Partial<LoadRequest> {
  /** Several requests per iteration, in order (instead of `url`). */
  requests?: LoadRequest[];
  /** Run an existing k6 script instead of a generated one. */
  script?: string;
  /** Virtual users. Default 1. */
  vus?: number;
  /** Test length, k6 syntax (`30s`, `2m`). Default `10s` unless `iterations` is set. */
  duration?: string;
  /** Total iterations shared by the VUs (instead of `duration`). */
  iterations?: number;
  /** Ramp from 0 to `vus` over this time first (k6 syntax). */
  rampUp?: string;
  /** Pause per iteration in seconds (think time). Default 0. */
  sleepSeconds?: number;
  thresholds?: LoadThresholds;
  /** Base for relative URLs. Default: `testfly.api.baseUrl`, `testfly.baseUrl`, then `use.baseURL`. */
  baseUrl?: string;
  /** Extra environment for k6 (`__ENV` in scripts). */
  env?: Record<string, string>;
}

/** Summary of a k6 run. Durations are in ms. @public */
export interface LoadResult {
  /** All thresholds held (k6 exit code 0). */
  passed: boolean;
  /** Thresholds that were crossed, as `metric: expression`. */
  failedThresholds: string[];
  requests: number;
  requestsPerSecond: number;
  /** Share of failed requests, 0..1. */
  errorRate: number;
  /** Share of passed checks, 0..1 (generated scripts check for a 2xx/3xx status). */
  checksRate: number;
  durationMs: { avg: number; min: number; med: number; max: number; p90: number; p95: number; p99: number };
  /** The k6 `--summary-export` JSON. */
  raw: unknown;
  /** Throws `TF_LOAD_THRESHOLDS_FAILED` unless every threshold held. */
  assertPassed(): void;
}

/** Builds the k6 script for `options`; URLs must already be absolute. @internal */
export function buildScript(options: LoadRunOptions & { requests: LoadRequest[] }): string {
  const thresholds: Record<string, string[]> = {};
  const t = options.thresholds ?? {};
  const duration: string[] = [];
  if (t.p95Ms !== undefined) duration.push(`p(95)<${t.p95Ms}`);
  if (t.p99Ms !== undefined) duration.push(`p(99)<${t.p99Ms}`);
  if (duration.length) thresholds.http_req_duration = duration;
  if (t.errorRate !== undefined) thresholds.http_req_failed = [`rate<${t.errorRate}`];

  const vus = options.vus ?? 1;
  const k6Options: Record<string, unknown> = { thresholds };
  if (options.rampUp) {
    k6Options.stages = [
      { duration: options.rampUp, target: vus },
      { duration: options.duration ?? '10s', target: vus },
    ];
  } else if (options.iterations !== undefined) {
    k6Options.vus = vus;
    k6Options.iterations = options.iterations;
  } else {
    k6Options.vus = vus;
    k6Options.duration = options.duration ?? '10s';
  }

  const calls = options.requests
    .map((r) => {
      const method = (r.method ?? 'GET').toUpperCase();
      const body = r.body === undefined ? 'null' : JSON.stringify(typeof r.body === 'string' ? r.body : JSON.stringify(r.body));
      const headers = { ...(typeof r.body === 'object' && r.body !== null ? { 'Content-Type': 'application/json' } : {}), ...r.headers };
      return `  check(http.request(${JSON.stringify(method)}, ${JSON.stringify(r.url)}, ${body}, { headers: ${JSON.stringify(headers)}, tags: { name: ${JSON.stringify(`${method} ${r.url}`)} } }), { 'status is 2xx/3xx': (res) => res.status >= 200 && res.status < 400 });`;
    })
    .join('\n');
  const pause = options.sleepSeconds ? `\n  sleep(${options.sleepSeconds});` : '';
  return `// Generated by @testfly/playwright load.run()
import http from 'k6/http';
import { check, sleep } from 'k6';

export const options = ${JSON.stringify(k6Options, null, 2)};

export default function () {
${calls}${pause}
}
`;
}

type Metric = Record<string, unknown> & { thresholds?: Record<string, boolean> };

/** Reads a k6 `--summary-export` file into a {@link LoadResult}. @internal */
export function parseSummary(raw: unknown, exitCode: number): LoadResult {
  const metrics = ((raw as { metrics?: Record<string, Metric> })?.metrics ?? {}) as Record<string, Metric>;
  const num = (m: Metric | undefined, key: string): number => (typeof m?.[key] === 'number' ? (m[key] as number) : 0);
  const d = metrics.http_req_duration;
  const failedThresholds: string[] = [];
  for (const [name, m] of Object.entries(metrics)) {
    // In the summary, true means the threshold was crossed.
    for (const [expr, crossed] of Object.entries(m.thresholds ?? {})) if (crossed) failedThresholds.push(`${name}: ${expr}`);
  }
  const passed = exitCode === 0 && failedThresholds.length === 0;
  return {
    passed,
    failedThresholds,
    requests: num(metrics.http_reqs, 'count'),
    requestsPerSecond: num(metrics.http_reqs, 'rate'),
    errorRate: num(metrics.http_req_failed, 'value'),
    checksRate: metrics.checks ? num(metrics.checks, 'value') : 1,
    durationMs: { avg: num(d, 'avg'), min: num(d, 'min'), med: num(d, 'med'), max: num(d, 'max'), p90: num(d, 'p(90)'), p95: num(d, 'p(95)'), p99: num(d, 'p(99)') },
    raw,
    assertPassed() {
      if (passed) return;
      throw new TestFlyError('TF_LOAD_THRESHOLDS_FAILED', `Load test thresholds failed: ${failedThresholds.join(', ') || `k6 exited with ${exitCode}`}`, {
        hint: 'Read the k6-summary attachment; raise the limits only if the new numbers are expected.',
        details: { failedThresholds, p95Ms: d?.['p(95)'], errorRate: metrics.http_req_failed?.value },
      });
    },
  };
}

/** Runs k6 on `scriptPath`, writing the summary next to it. @internal */
export async function runK6(k6Path: string, scriptPath: string, env: Record<string, string>, timeoutMs: number): Promise<LoadResult> {
  const summaryPath = path.join(path.dirname(scriptPath), 'k6-summary.json');
  const args = ['run', '--quiet', '--no-color', '--summary-trend-stats', 'avg,min,med,max,p(90),p(95),p(99)', '--summary-export', summaryPath, scriptPath];
  const { code, output } = await new Promise<{ code: number; output: string }>((resolve, reject) => {
    const child = spawn(k6Path, args, { env: { ...process.env, ...env }, stdio: ['ignore', 'pipe', 'pipe'] });
    let output = '';
    const keep = (chunk: Buffer) => {
      output = (output + chunk.toString()).slice(-8_000);
    };
    child.stdout.on('data', keep);
    child.stderr.on('data', keep);
    const timer = setTimeout(() => child.kill('SIGKILL'), timeoutMs);
    child.on('error', (err: NodeJS.ErrnoException) => {
      clearTimeout(timer);
      reject(
        err.code === 'ENOENT'
          ? new TestFlyError('TF_LOAD_K6_MISSING', `k6 not found at "${k6Path}".`, {
              hint: 'Install k6 (https://grafana.com/docs/k6/latest/set-up/install-k6/) or set testfly.load.k6Path.',
              cause: err,
            })
          : new TestFlyError('TF_LOAD_RUN_FAILED', `k6 could not start: ${err.message}`, { cause: err }),
      );
    });
    child.on('close', (code, signal) => {
      clearTimeout(timer);
      resolve({ code: code ?? (signal ? -1 : 0), output });
    });
  });
  // 0: thresholds held, 99: thresholds crossed; anything else means k6 itself failed.
  if ((code !== 0 && code !== 99) || !fs.existsSync(summaryPath)) {
    throw new TestFlyError('TF_LOAD_RUN_FAILED', `k6 exited with ${code === -1 ? `a timeout after ${timeoutMs} ms` : `code ${code}`} without a result.\n${output.trim().split('\n').slice(-15).join('\n')}`, {
      hint: 'Check the script and the target URL; the k6 output above shows the cause.',
      details: { exitCode: code, script: scriptPath },
    });
  }
  return parseSummary(JSON.parse(fs.readFileSync(summaryPath, 'utf8')), code);
}
